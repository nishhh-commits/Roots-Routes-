import { useState } from 'react'
import { usageUnits } from '../../data/hotel'
import type { MonthlyUsage } from '../../types/hotel'
import type { Reading } from '../../types/reading'

type MonthlyUsageWithSource = MonthlyUsage & {
  source?: 'demo' | 'manual'
}

type Mode = 'Demo Hotel' | 'Manual Entry' | 'Simulated Device Feed'

const modes: Mode[] = [
  'Demo Hotel',
  'Manual Entry',
  'Simulated Device Feed',
]

const sourceLabel = {
  demo: 'Demo reading',
  manual: 'Manual entry',
}

const sourceStyle = {
  demo: 'bg-sand-200 text-ink-700',
  manual: 'bg-leaf-100 text-leaf-700',
}

type Props = {
  usage: MonthlyUsageWithSource[]
  feed: Reading[]
}

export default function DataSources({ usage, feed }: Props) {
  const [mode, setMode] = useState<Mode>('Demo Hotel')

  const first = usage[0]
  const last = usage[usage.length - 1]

  const demoRows = usage.filter(
    (item) => (item.source ?? 'demo') === 'demo',
  )

  const manualRows = usage.filter(
    (item) => item.source === 'manual',
  )

  const simulated = feed.filter(
    (item) => item.source === 'demo',
  )

  const sources = [
    {
      name: 'Demo readings',
      state: `${demoRows.length} month(s) loaded`,
      active: demoRows.length > 0,
      note: 'Sample figures supplied with the prototype.',
    },
    {
      name: 'Manual entries',
      state: `${manualRows.length} month(s) recorded`,
      active: manualRows.length > 0,
      note: 'Typed in by hotel staff using the form above.',
    },
    {
      name: 'Simulated device feed',
      state:
        simulated.length > 0
          ? `${simulated.length} reading(s) received`
          : 'No readings yet',
      active: simulated.length > 0,
      note: 'Generated by the Simulate button. No physical meter is connected.',
    },
    {
      name: 'Connected devices',
      state: 'None connected',
      active: false,
      note: 'No smart meters or sensors are connected, so no figure here is a real device measurement.',
    },
  ]

  const monthlyRows =
    mode === 'Demo Hotel' ? demoRows : manualRows

  return (
    <section className="relative mt-12">
      <h2 className="text-2xl font-semibold text-plum-900">
        Where this data comes from
      </h2>

      <p className="mt-1 text-sm text-ink-500">
        {first && last
          ? `Reporting period: ${first.month} to ${last.month}, monthly totals.`
          : 'No monthly reporting data available.'}{' '}
        The charts show demo and manual monthly totals only.
        Simulated feed readings are kept separate.
      </p>

      <div className="mt-4 w-56 rotate-1 border border-terracotta/40 bg-[#FFF1D8] p-4 shadow-sm md:absolute md:right-0 md:top-0">
        <p className="font-type text-sm text-ink-900">
          Demo data, not live sensors!
        </p>
      </div>

      <ul className="mt-4 max-w-2xl">
        {sources.map((source) => (
          <li
            key={source.name}
            className="flex gap-3 border-t border-dashed border-sand-300 py-3"
          >
            <span
              aria-hidden="true"
              className={`mt-2 h-2 w-2 shrink-0 rounded-full ${
                source.active ? 'bg-sage' : 'bg-sand-300'
              }`}
            />

            <div>
              <p className="text-ink-900">
                {source.name}{' '}
                <span className="font-type text-sm text-ink-500">
                  · {source.state}
                </span>
              </p>

              <p className="text-sm text-ink-700">
                {source.note}
              </p>
            </div>
          </li>
        ))}
      </ul>

      <div
        className="mt-6 flex flex-wrap gap-2"
        role="group"
        aria-label="Data source"
      >
        {modes.map((item) => (
          <button
            key={item}
            onClick={() => setMode(item)}
            aria-pressed={mode === item}
            className={
              mode === item
                ? 'rounded-full bg-plum-700 px-4 py-1.5 text-sm text-cream-50'
                : 'rounded-full border border-sand-300 px-4 py-1.5 text-sm text-ink-700 hover:bg-paper-clean'
            }
          >
            {item}
          </button>
        ))}
      </div>

      <div className="mt-4 max-w-2xl overflow-x-auto">
        {mode === 'Simulated Device Feed' ? (
          simulated.length === 0 ? (
            <p className="border-t border-dashed border-sand-300 py-3 text-ink-500">
              No simulated readings received yet.
            </p>
          ) : (
            <table className="w-full text-left text-sm">
              <thead>
                <tr className="border-t border-dashed border-sand-300 text-ink-500">
                  <th className="py-2 font-medium">Received</th>
                  <th className="py-2 font-medium">Resource</th>
                  <th className="py-2 font-medium">Value</th>
                  <th className="py-2 font-medium">Device</th>
                  <th className="py-2 font-medium">Source</th>
                </tr>
              </thead>

              <tbody>
                {[...simulated].reverse().map((item) => (
                  <tr
                    key={item.id}
                    className="border-t border-dashed border-sand-300 text-ink-700"
                  >
                    <td className="py-2">
                      {new Date(item.recordedAt).toLocaleString('en-IN')}
                    </td>
                    <td className="py-2 capitalize">
                      {item.resource}
                    </td>
                    <td className="py-2">
                      {item.value} {item.unit}
                    </td>
                    <td className="py-2">
                      {item.deviceId ?? 'Demo'}
                    </td>
                    <td className="py-2">
                      <span className="rounded bg-plum-100 px-2 py-0.5 text-xs text-plum-700">
                        Demo reading
                      </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )
        ) : monthlyRows.length === 0 ? (
          <p className="border-t border-dashed border-sand-300 py-3 text-ink-500">
            {mode === 'Manual Entry'
              ? 'No manual entries yet. Use the form above to log a month.'
              : 'No demo months loaded.'}
          </p>
        ) : (
          <table className="w-full text-left text-sm">
            <thead>
              <tr className="border-t border-dashed border-sand-300 text-ink-500">
                <th className="py-2 font-medium">Month</th>
                <th className="py-2 font-medium">
                  Water ({usageUnits.water})
                </th>
                <th className="py-2 font-medium">
                  Energy ({usageUnits.energy})
                </th>
                <th className="py-2 font-medium">
                  Waste ({usageUnits.waste})
                </th>
                <th className="py-2 font-medium">Source</th>
              </tr>
            </thead>

            <tbody>
              {monthlyRows.map((item, index) => {
                const source = item.source ?? 'demo'

                return (
                  <tr
                    key={`${item.month}-${index}`}
                    className="border-t border-dashed border-sand-300 text-ink-700"
                  >
                    <td className="py-2">{item.month}</td>
                    <td className="py-2">{item.water}</td>
                    <td className="py-2">{item.energy}</td>
                    <td className="py-2">{item.waste}</td>
                    <td className="py-2">
                      <span
                        className={`rounded px-2 py-0.5 text-xs ${sourceStyle[source]}`}
                      >
                        {sourceLabel[source]}
                      </span>
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        )}
      </div>
    </section>
  )
}